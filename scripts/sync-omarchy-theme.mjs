#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  parseOmarchyColorsToml,
  resolveOmarchyPalette,
  buildOvataTokenMap,
  buildOmarchyStylesheet,
  buildOmarchyThemeManifest,
} from '../src/omarchy-colors.mjs';

const repoRoot = fileURLToPath(new URL('../', import.meta.url));
const defaultStateDir = join(homedir(), '.local', 'state', 'omarchy', 'current');
const systemThemesDir = '/usr/share/omarchy/themes';

function formatThemeName(rawName) {
  const cleaned = rawName.trim();
  if (!cleaned) return 'Active';
  return cleaned
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

const args = process.argv.slice(2);
let colorsFile = join(defaultStateDir, 'theme', 'colors.toml');
let themeNameFile = join(defaultStateDir, 'theme.name');
let explicitThemeName = null;
let writeFiles = false;

for (let i = 0; i < args.length; i++) {
  const arg = args[i];
  if (arg === '--write') {
    writeFiles = true;
  } else if (arg === '--colors-file' && args[i + 1]) {
    colorsFile = resolve(args[++i]);
  } else if (arg === '--theme-name' && args[i + 1]) {
    explicitThemeName = args[++i];
  } else {
    console.error(
      'Usage: node scripts/sync-omarchy-theme.mjs [--colors-file <path>] [--theme-name <name>] [--write]',
    );
    process.exit(2);
  }
}

const rawToml = readFileSync(colorsFile, 'utf8');
const parsedColors = parseOmarchyColorsToml(rawToml);
const rawSlug = existsSync(themeNameFile)
  ? readFileSync(themeNameFile, 'utf8').trim().toLowerCase()
  : 'active';
const detectedName =
  explicitThemeName ??
  (existsSync(themeNameFile)
    ? formatThemeName(readFileSync(themeNameFile, 'utf8'))
    : 'Active');

const existingManifestPath = join(repoRoot, 'manifest.json');
const existingManifest = existsSync(existingManifestPath)
  ? JSON.parse(readFileSync(existingManifestPath, 'utf8'))
  : {};

const manifest = buildOmarchyThemeManifest(parsedColors, {
  id: existingManifest.id ?? 'omarchy-theme-for-ovata',
  name: existingManifest.name ?? 'Omarchy Theme for Ovata',
  version: '1.2.0',
  author: existingManifest.author ?? 'L3SSE',
  platforms: existingManifest.platforms ?? ['linux'],
  themeName: detectedName,
});

const stylesheet = buildOmarchyStylesheet(parsedColors, {
  themeName: detectedName,
});

/** @type {Record<string, { id: string; name: string; mode: 'dark' | 'light'; accent: string; background: string; foreground: string; tokens: Record<string, string> }>} */
const presets = {};

if (existsSync(systemThemesDir)) {
  const dirs = readdirSync(systemThemesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b));

  for (const slug of dirs) {
    const themeTomlPath = join(systemThemesDir, slug, 'colors.toml');
    if (!existsSync(themeTomlPath)) continue;
    try {
      const toml = parseOmarchyColorsToml(readFileSync(themeTomlPath, 'utf8'));
      const resolved = resolveOmarchyPalette(toml);
      presets[slug] = {
        id: slug,
        name: formatThemeName(slug),
        mode: resolved.mode,
        accent: resolved.accent,
        background: resolved.background,
        foreground: resolved.foreground,
        tokens: buildOvataTokenMap(resolved),
      };
    } catch {
      /* ignore malformed custom directories */
    }
  }
}

const activePalette = resolveOmarchyPalette(parsedColors);
const activeKey = presets[rawSlug] ? rawSlug : 'active';
if (!presets[activeKey]) {
  presets[activeKey] = {
    id: activeKey,
    name: detectedName,
    mode: activePalette.mode,
    accent: activePalette.accent,
    background: activePalette.background,
    foreground: activePalette.foreground,
    tokens: buildOvataTokenMap(activePalette),
  };
}

const activePaletteTs = `// Auto-generated by scripts/sync-omarchy-theme.mjs — do not edit manually.
export interface OmarchyPreset {
  readonly id: string;
  readonly name: string;
  readonly mode: 'dark' | 'light';
  readonly accent: string;
  readonly background: string;
  readonly foreground: string;
  readonly tokens: Readonly<Record<string, string>>;
}

export const DEFAULT_OMARCHY_PRESET_KEY = ${JSON.stringify(activeKey)} as const;
export const OMARCHY_PRESETS: Readonly<Record<string, OmarchyPreset>> = Object.freeze(${JSON.stringify(
  presets,
  null,
  2,
)});
`;

const serializedManifest = `${JSON.stringify(manifest, null, 2)}\n`;
if (writeFiles) {
  writeFileSync(existingManifestPath, serializedManifest, 'utf8');
  writeFileSync(join(repoRoot, 'styles.css'), stylesheet, 'utf8');
  writeFileSync(join(repoRoot, 'src', 'active-palette.ts'), activePaletteTs, 'utf8');
}
process.stdout.write(serializedManifest);
